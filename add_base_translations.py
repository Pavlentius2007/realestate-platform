def update_translations(lang: str, translations: dict):
    """Обновляет переводы в .po файле"""
    
    translations_dir = Path("backend/translations")
    po_file_path = translations_dir / lang / "LC_MESSAGES" / "messages.po"
    
    if not po_file_path.exists():
        print(f"❌ Файл {po_file_path} не найден")
        return 0
    
    try:
        po = polib.pofile(str(po_file_path))
        updated_count = 0
        
        for entry in po:
            if entry.msgid in translations and not entry.msgstr:
                entry.msgstr = translations[entry.msgid]
                updated_count += 1
        
        po.save(str(po_file_path))
        print(f"✅ {lang}: обновлено {updated_count} переводов")
        return updated_count
        
    except Exception as e:
        print(f"❌ Ошибка при обновлении {lang}: {e}")
        return 0

